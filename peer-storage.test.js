'use strict';
// 0.126.0: the channel state file's holder (peer-storage.js). node peer-storage.test.js
const assert = require('assert');
const fs = require('fs'); const os = require('os'); const path = require('path');
const { createPeerStorage, signedText, sha256hex, FILE_MAX } = require('./peer-storage');
let n = 0; const ok = (m) => { n++; console.log('  ok · ' + m); };
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ps-'));
const A = '02' + 'aa'.repeat(32), B = '03' + 'bb'.repeat(32);
const fp = (c) => c.repeat(64);
const file = (seed, len) => Buffer.alloc(len === undefined ? FILE_MAX : len, seed);
const logs = [];
const ps = createPeerStorage({ dataDir: dir, maxRecords: 2, log: (m) => logs.push(m) });

assert.strictEqual(ps.get(A), null); assert.strictEqual(ps.meta(A), null);
ok('nothing held: get and meta answer null');
assert.deepStrictEqual(ps.put(A, 1000, fp('1'), file(1)), { ok: true, version: 1000 });
let g = ps.get(A);
assert.strictEqual(g.version, 1000); assert.strictEqual(g.state_fp, fp('1')); assert.ok(g.file.equals(file(1))); assert.strictEqual(g.file.length, 65531);
assert.strictEqual(ps.meta(A).bytes, 65531);
ok('a 65,531-byte file is kept and handed back byte for byte, with its number and fingerprint');
assert.strictEqual(ps.put(A, 1001, fp('2'), file(2, FILE_MAX + 1)).code, 'too_large');
assert.ok(ps.get(A).file.equals(file(1)));
ok('65,532 bytes: refused, the held file untouched');
assert.deepStrictEqual(ps.put(A, 999, fp('3'), file(3)), { ok: false, code: 'lower_version', held_version: 1000 });
assert.deepStrictEqual(ps.put(A, 1000, fp('3'), file(3)), { ok: false, code: 'lower_version', held_version: 1000 });
assert.deepStrictEqual(ps.put(A, 1000, fp('1'), file(1)), { ok: true, version: 1000, same: true });
assert.ok(ps.get(A).file.equals(file(1)));
ok('a lower number is refused; the same number with another fingerprint is refused; the same file twice is accepted and writes nothing');
assert.strictEqual(ps.put(A, 2000, fp('4'), file(4, 500)).ok, true);
g = ps.get(A); assert.strictEqual(g.version, 2000); assert.ok(g.file.equals(file(4, 500)));
assert.strictEqual(fs.readdirSync(path.join(dir, 'peer-storage')).filter((f) => f.startsWith(A)).length, 2);
ok('a higher number replaces: the latest only (one file and its line per wallet)');
assert.strictEqual(ps.put(B, 5, fp('5'), file(5)).ok, true);
assert.strictEqual(ps.put('02' + 'cc'.repeat(32), 5, fp('6'), file(6)).code, 'full');
assert.strictEqual(ps.put(A, 3000, fp('7'), file(7)).ok, true);
ok('held for any wallet key up to the cap; at the cap a new wallet is refused, a held wallet still updates');
for (const [pk, v, f, b, code] of [['zz', 1, fp('1'), file(1), 'bad_key'], [A, 0, fp('1'), file(1), 'bad_version'], [A, 1.5, fp('1'), file(1), 'bad_version'], [A, 4000, 'xyz', file(1), 'bad_fingerprint'], [A, 4000, fp('1'), Buffer.alloc(0), 'bad_file'], [A, 4000, fp('1'), 'text', 'bad_file']]) assert.strictEqual(ps.put(pk, v, f, b).code, code);
ok('bad key, number, fingerprint or file: each refused by name');
fs.writeFileSync(path.join(dir, 'peer-storage', B + '.bin'), file(9));
assert.strictEqual(ps.get(B), null);
ok('a file that does not match its line is not handed back');
assert.strictEqual(signedText('put', 'ab'.repeat(32), 7, sha256hex(file(1))), 'lij-peer-storage-v1:put:' + 'ab'.repeat(32) + ':7:' + sha256hex(file(1)));
assert.strictEqual(signedText('get', 'cd'.repeat(32)), 'lij-peer-storage-v1:get:' + 'cd'.repeat(32));
assert.strictEqual(signedText('meta', 'cd'.repeat(32)), 'lij-peer-storage-v1:meta:' + 'cd'.repeat(32));
ok('what the node key signs: a put names the number and the file\'s hash; a read names the action and the nonce');
assert.ok(logs.some((l) => /kept 65531 bytes for 02aaaaaaaaaaaaaa — no\. 1000 \(first\)/.test(l)) && logs.some((l) => /no\. 2000 \(was no\. 1000\)/.test(l)));
ok('the journal names the wallet (16 characters), the size and both numbers');
fs.rmSync(dir, { recursive: true, force: true });
console.log('peer-storage: ' + n + ' checks passed');
